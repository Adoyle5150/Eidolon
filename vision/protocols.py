from typing import Protocol, Dict, List, Any, Optional

class ScreenCaptureProtocol(Protocol):
    def start(self) -> None: ...
    def stop(self) -> None: ...

class ContextInterpreterProtocol(Protocol):
    def analyze_screenshot(self, image_path: str) -> Optional[Dict[str, Any]]: ...

class EidolonVisionMemoryProtocol(Protocol):
    memory: List[Dict[str, Any]]
    def remember(self, context: Dict[str, Any]) -> None: ...
    def get_recent_contexts(self, count: int = 5) -> List[Dict[str, Any]]: ... 